"""Check that the configuration option macros expanded correctly in the built documentation.

For every '{{ configsetting(...) }}' macro call in the markdown sources, the
rendered page is checked against the configuration options exported from the
backend (docs/generated/inventree_settings.json, 'config' group):

- The configuration key exists
- A configuration table row is rendered, with the expected environment variable,
  config file key and default value, plus a (non-empty) description
- The row is within a table generated by the '{{ configtable() }}' macro

For every '{{ configtable() }}' call, a configuration table must be rendered.

Usage:
    python docs/ci/check_config.py [--site-dir <path>]
"""

import json
from pathlib import Path

from docs_checks import (
    GENERATED_DIR,
    Checker,
    MacroCall,
    Page,
    check_macro_errors,
    find_macro_calls,
    iter_pages,
    normalize,
    run,
    table_row,
)

SETTINGS_FILE = GENERATED_DIR / 'inventree_settings.json'

# Expected header of a configuration table (as rendered by the 'configtable' macro)
TABLE_HEADERS = ['Environment Variable', 'Configuration File', 'Default', 'Description']

# Default value text used by the 'configsetting' macro if no default is specified
NOT_SPECIFIED = '*Not Specified*'


def check_config_row(page: Page, call: MacroCall, key: str, setting: dict, checker):
    """Check the rendered table row for a configsetting macro call."""
    label = f'{page.label}:{call.line} configsetting("{key}")'

    elements = page.soup.select(f'span[title="{key}"]')

    if not checker.check(bool(elements), f'{label} not rendered'):
        return

    row = table_row(elements[0])

    if not checker.check(row is not None, f'{label} not rendered within a table'):
        return

    checker.check(
        row.headers == TABLE_HEADERS,
        f'{label} rendered in a table with unexpected headers {row.headers} (missing configtable()?)',
    )

    if not checker.check(
        len(row.cells) == len(TABLE_HEADERS),
        f'{label} row has {len(row.cells)} columns (expected {len(TABLE_HEADERS)})',
    ):
        return

    env_var, config_key, default, description = row.cells

    checker.check(
        env_var.get_text(strip=True) == key,
        f'{label} environment variable: expected "{key}", found "{env_var.get_text(strip=True)}"',
    )

    expected_key = setting.get('config_key')
    found_key = config_key.get_text(strip=True)

    if expected_key:
        code = config_key.find('code')
        checker.check(
            code is not None and code.get_text(strip=True) == expected_key,
            f'{label} config file key: expected "{expected_key}", found "{found_key}"',
        )
    else:
        checker.check(
            found_key == '-',
            f'{label} config file key: expected "-", found "{found_key}"',
        )

    expected_default = call.arg(1, 'default') or setting.get('default_value')

    if expected_default is None:
        expected_default = NOT_SPECIFIED

    checker.check(
        normalize(default.get_text(' ')) == normalize(str(expected_default)),
        f'{label} default: expected "{expected_default}", found "{default.get_text(" ", strip=True)}"',
    )

    checker.check(
        bool(description.get_text(strip=True)), f'{label} description is empty'
    )


def check_config(site_dir: Path, checker: Checker):
    """Check all configuration option macro calls against the rendered documentation."""
    with open(SETTINGS_FILE, encoding='utf-8') as f:
        config = json.load(f).get('config', {})

    total_settings = 0
    total_tables = 0

    for page in iter_pages(site_dir):
        calls, skipped = find_macro_calls(page, 'configsetting')
        tables, _ = find_macro_calls(page, 'configtable')

        checker.check(
            skipped == 0,
            f'{page.label}: {skipped} configsetting() calls with non-literal arguments cannot be checked',
        )

        if not calls and not tables:
            continue

        total_settings += len(calls)
        total_tables += len(tables)

        if not checker.check(
            page.output.exists(), f'{page.label}: Missing rendered page {page.output}'
        ):
            continue

        check_macro_errors(page, checker)

        rendered_tables = [
            table
            for table in page.soup.select('table')
            if [th.get_text(' ', strip=True) for th in table.select('thead th')]
            == TABLE_HEADERS
        ]

        checker.check(
            len(rendered_tables) == len(tables),
            f'{page.label}: Expected {len(tables)} configuration tables, found {len(rendered_tables)}',
        )

        for call in calls:
            key = call.arg(0, 'key')
            setting = config.get(key)

            if checker.check(
                setting is not None,
                f'{page.label}:{call.line} configsetting("{key}"): unknown configuration option',
            ):
                check_config_row(page, call, key, setting, checker)

    checker.check(total_settings > 0, 'No configsetting() calls found in documentation')
    print(
        f'  Checked {total_settings} configsetting() calls, {total_tables} configtable() calls'
    )


if __name__ == '__main__':
    run('Checking configuration option macros', check_config)
