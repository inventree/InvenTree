"""Validators for the stock app."""

from django.core.exceptions import ValidationError
from django.template import Template, TemplateSyntaxError
from django.utils.translation import gettext_lazy as _


def validate_batch_code_template(value):
    """Validate that the STOCK_BATCH_CODE_TEMPLATE setting is a valid template.

    An empty value is allowed (no batch code is generated by default).

    Note: The template is only compiled here, not rendered,
    as the rendering context depends on the data supplied at generation time.
    """
    template = str(value or '')

    if not template.strip():
        return

    try:
        Template(template)
    except TemplateSyntaxError as exc:
        raise ValidationError({
            'value': _('Invalid batch code template: {error}').format(error=exc)
        })
